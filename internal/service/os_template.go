// Default values for OS install parameters.
const (
	defaultTimezone        = "UTC"
	defaultLanguage        = "en_US"
	defaultKeyboardLayout  = "us"
	defaultDisk            = "/dev/sda"
	defaultPartitionScheme = "whole_disk"
	defaultNetmask         = "255.255.255.0"
)

// ValidationError represents an error caused by invalid user input.
// Handlers should distinguish these from internal errors and return 400.
type ValidationError struct {
	Err error
}

func (e *ValidationError) Error() string {
	return e.Err.Error()
}

func (e *ValidationError) Unwrap() error {
	return e.Err
}


// OsTemplateService generates OS installation configuration files.
type OsTemplateService struct{}

// NewOsTemplateService creates a new OsTemplateService.
func NewOsTemplateService() *OsTemplateService {
	return &OsTemplateService{}
}

// Generate dispatches to the appropriate template generator based on osType.
// Supported osType values: "debian", "ubuntu", "centos", "rhel".
func (s *OsTemplateService) Generate(osType string, params model.OsInstallParams) (string, error) {
	switch strings.ToLower(osType) {
	case "debian":
		return GeneratePreseed(params)
	case "ubuntu":
		return GenerateAutoinstall(params)
	case "centos", "rhel":
		return GenerateKickstart(params, "centos")
	case "rocky", "rockylinux":
		return GenerateKickstart(params, "rocky")
	case "alma", "almalinux":
		return GenerateKickstart(params, "alma")
	case "fedora":
		return GenerateKickstart(params, "fedora")
	case "opensuse", "opensuse-leap":
		return GenerateAutoYAST(params)
	default:
		return "", &ValidationError{Err: fmt.Errorf("unsupported os_type: %q", osType)}
	}
}

// applyDefaults fills in sensible defaults for empty fields.
func applyDefaults(p *model.OsInstallParams) {
	if p.Timezone == "" {
		p.Timezone = defaultTimezone
	}
	if p.Language == "" {
		p.Language = defaultLanguage
	}
	if p.KeyboardLayout == "" {
		p.KeyboardLayout = defaultKeyboardLayout
	}
	if p.Disk == "" {
		p.Disk = defaultDisk
	}
	if p.PartitionScheme == "" {
		p.PartitionScheme = defaultPartitionScheme
	}
	if p.Netmask == "" && p.IPAddress != "" {
		p.Netmask = defaultNetmask
	}
}

// validateParams checks that required fields are present.
func validateParams(p model.OsInstallParams) error {
	if strings.TrimSpace(p.Hostname) == "" {
		return &ValidationError{Err: fmt.Errorf("hostname is required")}
	}
	return nil
}

// isStaticNetwork returns true if an IP address is configured.
func isStaticNetwork(p model.OsInstallParams) bool {
	return strings.TrimSpace(p.IPAddress) != ""
}

// formatDNSServers converts comma-separated DNS servers to a space-separated string.
func formatDNSServers(dns string) string {
	parts := strings.Split(dns, ",")
	var cleaned []string
	for _, s := range parts {
		s = strings.TrimSpace(s)
		if s != "" {
			cleaned = append(cleaned, s)
		}
	}
	return strings.Join(cleaned, " ")
}

// formatPackages converts a package slice to a space-separated string.
func formatPackages(pkgs []string) string {
	return strings.Join(pkgs, " ")
}

