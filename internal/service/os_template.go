// autoinstallData holds processed data for the autoinstall template.
type autoinstallData struct {
	model.OsInstallParams
	IsStatic      bool
	NetmaskCIDR   string
	DNSServersList []string
}

// GenerateAutoinstall generates an Ubuntu 20.04+ autoinstall YAML configuration file.
func GenerateAutoinstall(p model.OsInstallParams) (string, error) {
	if err := validateParams(p); err != nil {
		return "", fmt.Errorf("autoinstall validation: %w", err)
	}
	applyDefaults(&p)

	tmpl, err := template.New("autoinstall").Parse(autoinstallTemplate)
	if err != nil {
		return "", fmt.Errorf("parsing autoinstall template: %w", err)
	}

	// Convert netmask to CIDR notation.
	netmaskCIDR := "24"
	if p.Netmask != "" {
		netmaskCIDR = netmaskToCIDR(p.Netmask)
	}

	// Parse DNS servers into a list.
	var dnsList []string
	if p.DNSServers != "" {
		parts := strings.Split(p.DNSServers, ",")
		for _, s := range parts {
			s = strings.TrimSpace(s)
			if s != "" {
				dnsList = append(dnsList, s)
			}
		}
	}

	data := autoinstallData{
		OsInstallParams:  p,
		IsStatic:         isStaticNetwork(p),
		NetmaskCIDR:      netmaskCIDR,
		DNSServersList:   dnsList,
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("executing autoinstall template: %w", err)
	}
	return buf.String(), nil
}

// netmaskToCIDR converts a netmask like "255.255.255.0" to CIDR prefix like "24".
func netmaskToCIDR(mask string) string {
	bits := strings.Split(mask, ".")
	if len(bits) != 4 {
		return "24"
	}
	var cidr int
	for _, octet := range bits {
		val := 0
		for _, ch := range octet {
			val = val*10 + int(ch-'0')
		}
		cidr += countBits(val)
	}
	return fmt.Sprintf("%d", cidr)
}

// countBits counts the number of set bits in an integer.
func countBits(n int) int {
	count := 0
	for n > 0 {
		count += n & 1
		n >>= 1
	}
	return count
}
