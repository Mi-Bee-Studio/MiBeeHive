let currentLang = localStorage.getItem('mibeehive_lang') || 'zh';
var _tWarnedKeys = new Set();
function t(key, params) {
  var s = (I18N[currentLang] && I18N[currentLang][key]);
  if (s === undefined) {
    if (!_tWarnedKeys.has(key)) {
      _tWarnedKeys.add(key);
      console.warn('[i18n] Missing key:', key);
    }
    s = key;
  }
  if (params) {
    for (var k in params) s = s.replace('{' + k + '}', params[k]);
  }
  return s;
}
function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('mibeehive_lang', lang);
  document.documentElement.lang = lang;
  updateNavActive();
  if (window.renderCurrentPageContent) window.renderCurrentPageContent();
  if (typeof Shell !== 'undefined' && Shell.updatePageTitle) {
    var route = Router.getCurrentRoute();
    if (route) Shell.updatePageTitle(route);
  }
  // Notify Preact components of language change
  if (window.App) window.App.emit('language:changed', lang);
}


// ── Preact Context Integration ──────────────────────────────────
(function() {
  var PB = window.PreactBridge;
  if (!PB) return; // Preact not loaded, skip

  // Create context with defaults matching global state
  window.I18nContext = PB.createContext({ t: t, lang: currentLang, setLang: setLang });

  // Provider component — wraps app tree to provide reactive i18n state
  window.I18nProvider = function I18nProvider(props) {
    var _s = PB.useState(currentLang);
    var lang = _s[0];
    var setLangState = _s[1];

    var setLangWrapper = PB.useCallback(function (newLang) {
      setLangState(newLang);
      setLang(newLang);
    }, []);

    // Sync with global language changes (from vanilla code)
    PB.useEffect(function () {
      if (!window.App) return;
      function handleLangChange(lang) {
        setLangState(lang);
      }
      window.App.on('language:changed', handleLangChange);
      return function () { window.App.off('language:changed', handleLangChange); };
    }, []);

    var ctxVal = PB.useMemo(function () {
      return { t: t, lang: lang, setLang: setLangWrapper };
    }, [lang]);

    return PB.h(window.I18nContext.Provider, { value: ctxVal }, props.children);
  };

  // Hook for Preact components
  window.useI18n = function useI18n() {
    return PB.useContext(window.I18nContext);
  };
})();